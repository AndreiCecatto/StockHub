-- V8: complementos da NF-e (RN-53 a RN-60): seguro, outras despesas, rateio por item, pagamento e parcelas.
-- Apenas ACRESCENTA colunas (todas anulaveis) e tabelas novas: notas ja importadas continuam como estao
-- (os campos novos ficam NULL e as telas simplesmente nao mostram o que nao foi guardado). Nada e apagado.

ALTER TABLE nota_fiscal
    ADD COLUMN valor_seguro NUMERIC(14, 2),
    ADD COLUMN valor_outras NUMERIC(14, 2),
    ADD CONSTRAINT ck_nota_fiscal_seguro CHECK (valor_seguro IS NULL OR valor_seguro >= 0),
    ADD CONSTRAINT ck_nota_fiscal_outras CHECK (valor_outras IS NULL OR valor_outras >= 0);

-- Por item: desconto do proprio item e a parte de frete, seguro e outras despesas que entrou no custo
-- (rateada pelo sistema ou informada pelo emitente no item), mais o custo unitario resultante.
ALTER TABLE nota_fiscal_item
    ADD COLUMN valor_desconto NUMERIC(14, 2),
    ADD COLUMN valor_frete    NUMERIC(14, 2),
    ADD COLUMN valor_seguro   NUMERIC(14, 2),
    ADD COLUMN valor_outras   NUMERIC(14, 2),
    ADD COLUMN custo_unitario NUMERIC(14, 4),
    ADD CONSTRAINT ck_nota_fiscal_item_custo CHECK (custo_unitario IS NULL OR custo_unitario >= 0);

-- Como a nota foi paga (pag/detPag). Somente leitura: base para contas a pagar.
CREATE TABLE nota_fiscal_pagamento (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_fiscal_id INTEGER        NOT NULL,
    ordem          SMALLINT       NOT NULL,
    forma          VARCHAR(2)     NOT NULL,
    descricao      VARCHAR(60)    NOT NULL,
    valor          NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_nota_fiscal_pagamento_nota FOREIGN KEY (nota_fiscal_id) REFERENCES nota_fiscal (id),
    CONSTRAINT ck_nota_fiscal_pagamento_valor CHECK (valor >= 0)
);
CREATE INDEX idx_nota_fiscal_pagamento_nota ON nota_fiscal_pagamento (nota_fiscal_id);

-- Parcelas e vencimentos (cobr/dup).
CREATE TABLE nota_fiscal_parcela (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_fiscal_id INTEGER        NOT NULL,
    numero         SMALLINT       NOT NULL,
    vencimento     DATE,
    valor          NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_nota_fiscal_parcela_nota FOREIGN KEY (nota_fiscal_id) REFERENCES nota_fiscal (id),
    CONSTRAINT ck_nota_fiscal_parcela_valor CHECK (valor >= 0)
);
CREATE INDEX idx_nota_fiscal_parcela_nota ON nota_fiscal_parcela (nota_fiscal_id);
