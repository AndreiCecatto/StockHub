-- V4: importacao de NF-e de compra (RN-15 em diante). So cria tabelas e indices novos.

-- Nota fiscal ja importada. UNIQUE (loja, chave) garante a idempotencia: a mesma nota nunca
-- entra duas vezes na mesma loja (mesmo numa corrida entre duas confirmacoes).
CREATE TABLE nota_fiscal (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_codigo    INTEGER        NOT NULL,
    chave_acesso      CHAR(44)       NOT NULL,
    modelo            SMALLINT,
    serie             INTEGER,
    numero            BIGINT,
    natureza_operacao VARCHAR(120),
    emitida_em        TIMESTAMP(6),
    parceiro_id       INTEGER,
    cnpj_destinatario VARCHAR(14),
    valor_produtos    NUMERIC(14, 2),
    valor_frete       NUMERIC(14, 2),
    valor_desconto    NUMERIC(14, 2),
    valor_total       NUMERIC(14, 2),
    importada_em      TIMESTAMP(6)   NOT NULL,
    CONSTRAINT fk_nota_fiscal_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo),
    CONSTRAINT fk_nota_fiscal_parceiro FOREIGN KEY (parceiro_id) REFERENCES parceiro (id),
    CONSTRAINT uk_nota_fiscal_usuario_chave UNIQUE (usuario_codigo, chave_acesso),
    CONSTRAINT ck_nota_fiscal_chave CHECK (chave_acesso ~ '^[0-9]{44}$')
);

CREATE INDEX idx_nota_fiscal_usuario_importada ON nota_fiscal (usuario_codigo, importada_em DESC);
CREATE INDEX idx_nota_fiscal_parceiro ON nota_fiscal (parceiro_id);

CREATE TABLE nota_fiscal_item (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_fiscal_id    INTEGER        NOT NULL,
    numero_item       SMALLINT       NOT NULL,
    codigo_fornecedor VARCHAR(60),
    ean               VARCHAR(14),
    descricao         VARCHAR(120),
    ncm               VARCHAR(8),
    cfop              CHAR(4),
    cfop_entrada      CHAR(4),
    unidade           VARCHAR(6),
    quantidade        NUMERIC(14, 4),
    valor_unitario    NUMERIC(21, 10),
    valor_total       NUMERIC(14, 2),
    produto_id        INTEGER,
    movimentacao_id   INTEGER,
    situacao          VARCHAR(20)    NOT NULL,
    CONSTRAINT fk_nota_fiscal_item_nota FOREIGN KEY (nota_fiscal_id) REFERENCES nota_fiscal (id),
    CONSTRAINT fk_nota_fiscal_item_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT fk_nota_fiscal_item_movimentacao FOREIGN KEY (movimentacao_id) REFERENCES movimentacao_estoque (id),
    CONSTRAINT ck_nota_fiscal_item_situacao CHECK (situacao IN ('IMPORTADO', 'IGNORADO', 'FRACIONADO'))
);

CREATE INDEX idx_nota_fiscal_item_nota ON nota_fiscal_item (nota_fiscal_id);
CREATE INDEX idx_nota_fiscal_item_produto ON nota_fiscal_item (produto_id);

-- Preparacao da importacao: o XML fica guardado ate o dono confirmar (ou expirar em 30 min).
-- A confirmacao SEMPRE relê este XML; nunca confia em dados reenviados pelo navegador.
CREATE TABLE importacao_nfe (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_codigo INTEGER      NOT NULL,
    token          UUID         NOT NULL,
    xml            TEXT         NOT NULL,
    sha256         CHAR(64),
    chave_acesso   CHAR(44),
    status         VARCHAR(12)  NOT NULL,
    criada_em      TIMESTAMP(6) NOT NULL,
    expira_em      TIMESTAMP(6) NOT NULL,
    nota_fiscal_id INTEGER,
    CONSTRAINT fk_importacao_nfe_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo),
    CONSTRAINT fk_importacao_nfe_nota FOREIGN KEY (nota_fiscal_id) REFERENCES nota_fiscal (id),
    CONSTRAINT uk_importacao_nfe_token UNIQUE (token),
    CONSTRAINT ck_importacao_nfe_status CHECK (status IN ('PENDENTE', 'CONFIRMADA', 'CANCELADA')),
    CONSTRAINT ck_importacao_nfe_xml_tamanho CHECK (length(xml) <= 2097152)
);

CREATE INDEX idx_importacao_nfe_usuario_status ON importacao_nfe (usuario_codigo, status);
