-- V1: esquema inicial do StockHub (reproduz o modelo JPA em org.example.stockhubspring.model)

CREATE TABLE usuario (
    codigo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(255) NOT NULL,
    email  VARCHAR(255) NOT NULL,
    senha  VARCHAR(255) NOT NULL,
    ativo  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE categoria (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(255) NOT NULL,
    descricao      TEXT,
    usuario_codigo INTEGER      NOT NULL,
    CONSTRAINT fk_categoria_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo)
);

CREATE TABLE produto (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(255)   NOT NULL,
    descricao      TEXT,
    preco          NUMERIC(38, 2) NOT NULL DEFAULT 0,
    quantidade     INTEGER        NOT NULL DEFAULT 0,
    estoque_minimo INTEGER        NOT NULL DEFAULT 0,
    categoria_id   INTEGER        NOT NULL,
    usuario_codigo INTEGER        NOT NULL,
    CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_produto_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo),
    CONSTRAINT ck_produto_preco CHECK (preco >= 0),
    CONSTRAINT ck_produto_quantidade CHECK (quantidade >= 0),
    CONSTRAINT ck_produto_estoque_minimo CHECK (estoque_minimo >= 0)
);

CREATE TABLE movimentacao_estoque (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id     INTEGER      NOT NULL,
    usuario_codigo INTEGER      NOT NULL,
    tipo           VARCHAR(20)  NOT NULL,
    quantidade     INTEGER      NOT NULL,
    observacao     TEXT,
    criado_em      TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_movimentacao_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT fk_movimentacao_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo),
    CONSTRAINT ck_movimentacao_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA', 'AJUSTE'))
);

-- Indices nas chaves estrangeiras (o PostgreSQL nao as cria automaticamente)
CREATE INDEX idx_categoria_usuario ON categoria (usuario_codigo);
CREATE INDEX idx_produto_categoria ON produto (categoria_id);
CREATE INDEX idx_produto_usuario ON produto (usuario_codigo);
CREATE INDEX idx_movimentacao_produto ON movimentacao_estoque (produto_id);
CREATE INDEX idx_movimentacao_usuario ON movimentacao_estoque (usuario_codigo);
