-- V3: base para compras/vendas futuras (custo e identificacao fiscal do produto, parceiro generico,
-- origem da movimentacao e CNPJ da loja). So ACRESCENTA colunas, tabelas e indices: nenhum dado
-- existente e apagado nem alterado (colunas novas entram com DEFAULT ou NULL).

-- ---------------------------------------------------------------------------
-- 1. Produto: custo (ultimo custo de compra), unidade, EAN e NCM. O preco de VENDA continua em "preco".
-- ---------------------------------------------------------------------------
ALTER TABLE produto
    ADD COLUMN custo   NUMERIC(14, 4) NOT NULL DEFAULT 0,
    ADD COLUMN unidade VARCHAR(6)     NOT NULL DEFAULT 'UN',
    ADD COLUMN ean     VARCHAR(14),
    ADD COLUMN ncm     VARCHAR(8);

ALTER TABLE produto
    ADD CONSTRAINT ck_produto_custo CHECK (custo >= 0),
    ADD CONSTRAINT ck_produto_ean CHECK (ean IS NULL OR (ean ~ '^[0-9]+$' AND length(ean) IN (8, 12, 13, 14))),
    ADD CONSTRAINT ck_produto_ncm CHECK (ncm IS NULL OR ncm ~ '^[0-9]{8}$');

CREATE INDEX idx_produto_usuario_ean ON produto (usuario_codigo, ean) WHERE ean IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 2. Parceiro: pessoa/empresa com quem a loja negocia (fornecedor hoje, cliente amanha)
-- ---------------------------------------------------------------------------
CREATE TABLE parceiro (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_codigo INTEGER      NOT NULL,
    documento      VARCHAR(14)  NOT NULL,
    nome           VARCHAR(255) NOT NULL,
    nome_fantasia  VARCHAR(255),
    uf             CHAR(2),
    eh_fornecedor  BOOLEAN      NOT NULL DEFAULT TRUE,
    eh_cliente     BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em      TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_parceiro_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo),
    CONSTRAINT uk_parceiro_usuario_documento UNIQUE (usuario_codigo, documento),
    -- CNPJ (14) ou CPF (11), so digitos
    CONSTRAINT ck_parceiro_documento CHECK (documento ~ '^([0-9]{11}|[0-9]{14})$')
);

CREATE INDEX idx_parceiro_usuario ON parceiro (usuario_codigo);

-- ---------------------------------------------------------------------------
-- 3. Movimentacao: origem opcional (de que documento veio). VENDA e OS entram quando existirem,
--    por uma nova migration que amplia o CHECK abaixo.
-- ---------------------------------------------------------------------------
ALTER TABLE movimentacao_estoque
    ADD COLUMN origem_tipo VARCHAR(20),
    ADD COLUMN origem_id   INTEGER;

ALTER TABLE movimentacao_estoque
    ADD CONSTRAINT ck_movimentacao_origem_par CHECK ((origem_tipo IS NULL) = (origem_id IS NULL)),
    ADD CONSTRAINT ck_movimentacao_origem_tipo CHECK (origem_tipo IS NULL OR origem_tipo IN ('NFE_COMPRA'));

CREATE INDEX idx_movimentacao_origem ON movimentacao_estoque (origem_tipo, origem_id);

-- ---------------------------------------------------------------------------
-- 4. Usuario (loja): CNPJ opcional, so digitos (o digito verificador e conferido na aplicacao)
-- ---------------------------------------------------------------------------
ALTER TABLE usuario
    ADD COLUMN cnpj VARCHAR(14);

ALTER TABLE usuario
    ADD CONSTRAINT ck_usuario_cnpj CHECK (cnpj IS NULL OR cnpj ~ '^[0-9]{14}$');
