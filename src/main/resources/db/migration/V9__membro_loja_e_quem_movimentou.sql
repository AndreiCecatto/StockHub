-- V9: separa a LOJA (a conta "usuario") das PESSOAS que operam a loja (membro_loja).
-- A tabela usuario e as colunas usuario_codigo continuam como estao: agora significam "a loja" (AD-13).
-- So acrescenta: nenhuma linha e apagada e nenhuma senha e alterada.
CREATE TABLE membro_loja (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_codigo INTEGER      NOT NULL,
    nome        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    senha       VARCHAR(255) NOT NULL,
    papel       VARCHAR(20)  NOT NULL,
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT fk_membro_loja_loja FOREIGN KEY (loja_codigo) REFERENCES usuario (codigo),
    CONSTRAINT uk_membro_loja_email UNIQUE (email),
    CONSTRAINT ck_membro_loja_papel CHECK (papel IN ('DONO', 'GERENTE', 'OPERADOR', 'VENDEDOR', 'MECANICO'))
);

CREATE INDEX idx_membro_loja_loja ON membro_loja (loja_codigo);
-- Cada loja tem um unico DONO
CREATE UNIQUE INDEX uk_membro_loja_um_dono ON membro_loja (loja_codigo) WHERE papel = 'DONO';

-- Cada conta existente vira o DONO da propria loja, com o mesmo e-mail e o MESMO hash de senha:
-- o login continua igual.
INSERT INTO membro_loja (loja_codigo, nome, email, senha, papel, ativo)
SELECT codigo, nome, email, senha, 'DONO', ativo FROM usuario;

