-- Contador por loja: o proximo numero e tirado com UPSERT atomico (sem buracos nem repeticao sob concorrencia)
CREATE TABLE os_contador (
    usuario_codigo INTEGER PRIMARY KEY,
    ultimo         INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_os_contador_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo)
);

-- Equipamento ou veiculo de um cliente (descricao livre + identificador opcional, como placa ou serie)
CREATE TABLE equipamento_cliente (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_codigo INTEGER      NOT NULL,
    parceiro_id    INTEGER      NOT NULL,
    descricao      VARCHAR(255) NOT NULL,
    identificador  VARCHAR(60),
    criado_em      TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT fk_equipamento_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo),
    CONSTRAINT fk_equipamento_parceiro FOREIGN KEY (parceiro_id) REFERENCES parceiro (id)
);
CREATE INDEX idx_equipamento_cliente ON equipamento_cliente (usuario_codigo, parceiro_id);

CREATE TABLE ordem_servico (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_codigo  INTEGER        NOT NULL,
    numero          INTEGER        NOT NULL,
    parceiro_id     INTEGER        NOT NULL,
    equipamento_id  INTEGER        NOT NULL,
    defeito         VARCHAR(1000)  NOT NULL,
    responsavel_id  INTEGER,
    status          VARCHAR(20)    NOT NULL DEFAULT 'ORCAMENTO',
    desconto        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total           NUMERIC(14, 2) NOT NULL DEFAULT 0,
    garantia_dias   INTEGER        NOT NULL DEFAULT 0,
    observacoes     VARCHAR(1000),
    criada_em       TIMESTAMP(6)   NOT NULL DEFAULT now(),
    aprovada_em     TIMESTAMP(6),
    iniciada_em     TIMESTAMP(6),
    concluida_em    TIMESTAMP(6),
    entregue_em     TIMESTAMP(6),
    cancelada_em    TIMESTAMP(6),
    criada_por_id   INTEGER,
    CONSTRAINT fk_os_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo),
    CONSTRAINT fk_os_parceiro FOREIGN KEY (parceiro_id) REFERENCES parceiro (id),
    CONSTRAINT fk_os_equipamento FOREIGN KEY (equipamento_id) REFERENCES equipamento_cliente (id),
    CONSTRAINT fk_os_responsavel FOREIGN KEY (responsavel_id) REFERENCES membro_loja (id),
    CONSTRAINT ux_os_numero UNIQUE (usuario_codigo, numero),
    CONSTRAINT ck_os_status CHECK (status IN
        ('ORCAMENTO', 'APROVADA', 'EM_EXECUCAO', 'CONCLUIDA', 'ENTREGUE', 'CANCELADA')),
    CONSTRAINT ck_os_desconto CHECK (desconto >= 0),
    CONSTRAINT ck_os_total CHECK (total >= 0),
    CONSTRAINT ck_os_garantia CHECK (garantia_dias BETWEEN 0 AND 3650)
);
CREATE INDEX idx_os_loja_status ON ordem_servico (usuario_codigo, status, criada_em DESC);
CREATE INDEX idx_os_parceiro ON ordem_servico (usuario_codigo, parceiro_id);

-- Peca usada: preco e custo gravados na hora de incluir; reserva_id/movimentacao_id ligam ao estoque
CREATE TABLE os_peca (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id            INTEGER        NOT NULL,
    produto_id       INTEGER        NOT NULL,
    quantidade       INTEGER        NOT NULL,
    preco_unitario   NUMERIC(14, 4) NOT NULL,
    custo_unitario   NUMERIC(14, 4) NOT NULL,
    reserva_id       INTEGER,
    movimentacao_id  INTEGER,
    CONSTRAINT fk_os_peca_os FOREIGN KEY (os_id) REFERENCES ordem_servico (id),
    CONSTRAINT fk_os_peca_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT fk_os_peca_reserva FOREIGN KEY (reserva_id) REFERENCES reserva_estoque (id),
    CONSTRAINT fk_os_peca_movimentacao FOREIGN KEY (movimentacao_id) REFERENCES movimentacao_estoque (id),
    CONSTRAINT ck_os_peca_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_os_peca_valores CHECK (preco_unitario >= 0 AND custo_unitario >= 0)
);
CREATE INDEX idx_os_peca_os ON os_peca (os_id);

CREATE TABLE os_servico (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id      INTEGER        NOT NULL,
    descricao  VARCHAR(255)   NOT NULL,
    valor      NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_os_servico_os FOREIGN KEY (os_id) REFERENCES ordem_servico (id),
    CONSTRAINT ck_os_servico_valor CHECK (valor >= 0)
);
CREATE INDEX idx_os_servico_os ON os_servico (os_id);
