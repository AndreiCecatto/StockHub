-- V10: base para vendas e OS (Etapa 5b, AD-14).
-- 1) A origem da movimentacao vira "documento de origem" (tipo_documento + documento_id).
-- 2) Preco de venda no movimento e no produto.
-- 3) Estorno: movimento contrario que aponta para o original (estorno_de_id), uma unica vez.
-- 4) Reserva de estoque.
-- So renomeia, acrescenta e converte valores: nenhuma linha e apagada.

-- ---------------------------------------------------------------------------
-- 1. Documento de origem
-- ---------------------------------------------------------------------------
ALTER TABLE movimentacao_estoque RENAME COLUMN origem_tipo TO tipo_documento;
ALTER TABLE movimentacao_estoque RENAME COLUMN origem_id TO documento_id;
ALTER TABLE movimentacao_estoque DROP CONSTRAINT ck_movimentacao_origem_par;
ALTER TABLE movimentacao_estoque DROP CONSTRAINT ck_movimentacao_origem_tipo;
ALTER INDEX idx_movimentacao_origem RENAME TO idx_movimentacao_documento;

-- A NF-e ja gravada vira COMPRA_NFE; o que nao tinha documento era lancamento manual
UPDATE movimentacao_estoque SET tipo_documento = 'COMPRA_NFE' WHERE tipo_documento = 'NFE_COMPRA';
UPDATE movimentacao_estoque SET tipo_documento = 'MANUAL' WHERE tipo_documento IS NULL;

ALTER TABLE movimentacao_estoque
    ALTER COLUMN tipo_documento SET NOT NULL,
    ALTER COLUMN tipo_documento SET DEFAULT 'MANUAL';

ALTER TABLE movimentacao_estoque
    ADD CONSTRAINT ck_movimentacao_tipo_documento CHECK (tipo_documento IN
        ('COMPRA_NFE', 'VENDA', 'OS', 'DEVOLUCAO', 'PERDA', 'INVENTARIO', 'MANUAL')),
    -- compra, venda e OS sempre apontam para o documento; o lancamento manual nunca
    ADD CONSTRAINT ck_movimentacao_documento_id CHECK (
        (tipo_documento IN ('COMPRA_NFE', 'VENDA', 'OS') AND documento_id IS NOT NULL)
        OR (tipo_documento = 'MANUAL' AND documento_id IS NULL)
        OR tipo_documento IN ('DEVOLUCAO', 'PERDA', 'INVENTARIO'));

-- ---------------------------------------------------------------------------
-- 2. Precos
-- ---------------------------------------------------------------------------
-- Preco de venda praticado no movimento (NULL = nao e uma venda ou nao foi informado)
ALTER TABLE movimentacao_estoque ADD COLUMN preco_unitario NUMERIC(14, 4);
ALTER TABLE movimentacao_estoque
    ADD CONSTRAINT ck_movimentacao_preco_nao_negativo CHECK (preco_unitario IS NULL OR preco_unitario >= 0);

-- Preco de venda do produto (NULL = vale o campo "preco" do cadastro)
ALTER TABLE produto ADD COLUMN preco_venda NUMERIC(14, 4);
ALTER TABLE produto
    ADD CONSTRAINT ck_produto_preco_venda CHECK (preco_venda IS NULL OR preco_venda >= 0);

-- ---------------------------------------------------------------------------
-- 3. Estorno
-- ---------------------------------------------------------------------------
ALTER TABLE movimentacao_estoque ADD COLUMN estorno_de_id INTEGER;
ALTER TABLE movimentacao_estoque
    ADD CONSTRAINT fk_movimentacao_estorno FOREIGN KEY (estorno_de_id) REFERENCES movimentacao_estoque (id),
    ADD CONSTRAINT ck_movimentacao_estorno_outro CHECK (estorno_de_id IS NULL OR estorno_de_id <> id);
-- Cada movimento so pode ser estornado uma vez (a regra vale mesmo sob concorrencia)
CREATE UNIQUE INDEX ux_movimentacao_estorno_unico ON movimentacao_estoque (estorno_de_id)
    WHERE estorno_de_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 4. Reserva de estoque
-- ---------------------------------------------------------------------------
CREATE TABLE reserva_estoque (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_codigo INTEGER      NOT NULL,
    produto_id     INTEGER      NOT NULL,
    quantidade     INTEGER      NOT NULL,
    documento_tipo VARCHAR(20)  NOT NULL,
    documento_id   INTEGER      NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'ATIVA',
    criada_em      TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT fk_reserva_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario (codigo),
    CONSTRAINT fk_reserva_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT ck_reserva_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_reserva_documento_tipo CHECK (documento_tipo IN ('VENDA', 'OS')),
    CONSTRAINT ck_reserva_status CHECK (status IN ('ATIVA', 'BAIXADA', 'CANCELADA'))
);

-- Soma das reservas ativas de um produto (saldo disponivel) e busca por documento
CREATE INDEX idx_reserva_produto_ativa ON reserva_estoque (produto_id) WHERE status = 'ATIVA';
CREATE INDEX idx_reserva_documento ON reserva_estoque (usuario_codigo, documento_tipo, documento_id);
